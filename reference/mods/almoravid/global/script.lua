function DrawSpecificCard(deckGUID,CardName,pos1,pos2)
    local found=false

    local DeckToDrawFrom= getObjectFromGUID(deckGUID)
    local deckContents = DeckToDrawFrom.getObjects()
	
    for _, object in ipairs(deckContents) do
        if object.name == CardName then

            local params = {
                 position = {pos1,6.64,pos2} ,
                 index = object.index,
				 flip = true
             }
            DeckToDrawFrom.takeObject(params)
			
            found = true
            break
        end
    end
    if found==false then broadcastToAll("Error with card setup : check card setup to see which need to be tucked under certain lords mat") end
end




